  let current = localStorage.getItem('ocgdbLang') || 'vi';
  if (!STRINGS[current]) current = 'vi';

  function t(key, vars) {
    const dict = STRINGS[current] || STRINGS.vi;
    let s = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : (STRINGS.vi[key] || key);
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
      });
    }
    return s;
  }

  function lang() {
    return current;
  }

  function setLang(l) {
    if (!STRINGS[l]) return;
    current = l;
    localStorage.setItem('ocgdbLang', l);
    document.documentElement.setAttribute('lang', l);
    applyI18n();
    document.dispatchEvent(new CustomEvent('ocgdb:langchange', { detail: { lang: l } }));
  }

  function applyI18n(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
  }

  document.documentElement.setAttribute('lang', current);

  window.I18N = { t, lang, setLang, applyI18n };
